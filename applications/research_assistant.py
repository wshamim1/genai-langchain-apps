"""
Research Assistant Application

An intelligent research assistant that can:
- Search for information
- Perform calculations
- Read and write files
- Analyze data
- Generate reports

This application demonstrates the integration of:
- Chat Models (OpenAI)
- Agents (ReAct Agent)
- Tools (Calculator, Search, File Operations)
- Agent Executor
"""

import os
import sys
from datetime import datetime
from dotenv import load_dotenv

# Add src to path
sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), '..')))

from src.chat_models import OpenAIChatModel
from src.tools import CalculatorTool, SearchTool, FileReadTool, FileWriteTool, FileListTool
from src.agents import ReActAgent, AgentExecutor

# Load environment variables
load_dotenv()


class ResearchAssistant:
    """Intelligent Research Assistant using Agents and Tools.
    
    This assistant can:
    - Answer questions using search
    - Perform calculations
    - Read and analyze files
    - Generate research reports
    - Save findings to files
    """
    
    def __init__(
        self,
        model_name: str = "gpt-3.5-turbo",
        temperature: float = 0.0,
        workspace_dir: str = "data/research"
    ):
        """Initialize the research assistant.
        
        Args:
            model_name: LLM model to use
            temperature: Temperature for generation
            workspace_dir: Directory for research files
        """
        # Check for API key
        if not os.getenv("OPENAI_API_KEY"):
            raise ValueError("OPENAI_API_KEY not found in environment variables")
        
        # Create workspace directory if it doesn't exist
        os.makedirs(workspace_dir, exist_ok=True)
        self.workspace_dir = workspace_dir
        
        # Initialize LLM
        self.llm = OpenAIChatModel(
            model_name=model_name,
            temperature=temperature
        )
        
        # Initialize tools
        self.tools = [
            CalculatorTool.create(),
            SearchTool.create(),
            FileReadTool.create(base_directory=workspace_dir),
            FileWriteTool.create(base_directory=workspace_dir),
            FileListTool.create(base_directory=workspace_dir),
        ]
        
        # Initialize agent
        self.agent = ReActAgent.create(
            llm=self.llm,
            tools=self.tools,
            verbose=True,
            max_iterations=10
        )
        
        # Initialize executor
        self.executor = AgentExecutor.create(
            agent=self.agent,
            tools=self.tools,
            max_iterations=10,
            verbose=True,
            return_intermediate_steps=True
        )
        
        print("✅ Research Assistant initialized!")
        print(f"📁 Workspace: {workspace_dir}")
        print(f"🔧 Available tools: {', '.join([tool.name for tool in self.tools])}\n")
    
    def research(self, task: str) -> dict:
        """Execute a research task.
        
        Args:
            task: The research task description
            
        Returns:
            Dictionary with output and intermediate steps
        """
        print(f"\n{'='*80}")
        print(f"  🔬 Research Task")
        print(f"{'='*80}")
        print(f"📋 Task: {task}\n")
        
        result = self.executor.run(task)
        
        print(f"\n{'='*80}")
        print(f"  ✅ Research Complete")
        print(f"{'='*80}\n")
        
        return result
    
    def generate_report(self, topic: str, findings: str) -> str:
        """Generate a research report.
        
        Args:
            topic: The research topic
            findings: The research findings
            
        Returns:
            Path to the generated report
        """
        timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
        filename = f"research_report_{timestamp}.txt"
        
        report_content = f"""# Research Report: {topic}
Generated: {datetime.now().strftime("%Y-%m-%d %H:%M:%S")}

## Findings

{findings}

## Conclusion

This report was automatically generated by the Research Assistant.
"""
        
        # Save report
        filepath = os.path.join(self.workspace_dir, filename)
        with open(filepath, 'w', encoding='utf-8') as f:
            f.write(report_content)
        
        print(f"📄 Report saved: {filepath}")
        return filepath


