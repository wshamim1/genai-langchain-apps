def interactive_mode():
    """Run the assistant in interactive mode."""
    print("\n" + "="*80)
    print("  💬 Research Assistant - Interactive Mode")
    print("="*80)
    print("\nCommands:")
    print("  - Describe your research task")
    print("  - Type 'quit' or 'exit' to end")
    print("  - Type 'help' for examples")
    print("\n" + "="*80 + "\n")
    
    try:
        assistant = ResearchAssistant()
        
        while True:
            try:
                task = input("\n🔬 Research Task: ").strip()
                
                if not task:
                    continue
                
                if task.lower() in ['quit', 'exit', 'q']:
                    print("\n👋 Goodbye!\n")
                    break
                
                if task.lower() == 'help':
                    print("\n📖 Example Tasks:")
                    print("  1. Calculate 15% of 250 and save to results.txt")
                    print("  2. Search for information about AI and summarize it")
                    print("  3. List all files and create an inventory")
                    print("  4. Read data.txt and analyze the content\n")
                    continue
                
                result = assistant.research(task)
                print(f"\n✅ Result: {result['output']}\n")
                
            except KeyboardInterrupt:
                print("\n\n👋 Goodbye!\n")
                break
            except Exception as e:
                print(f"\n❌ Error: {str(e)}\n")
    
    except ValueError as e:
        print(f"\n❌ Configuration Error: {str(e)}")
        print("Please set OPENAI_API_KEY in your .env file\n")


def main():
    """Main entry point."""
    import argparse
    
    parser = argparse.ArgumentParser(description="Research Assistant Application")
    parser.add_argument(
        '--mode',
        choices=['demo', 'interactive'],
        default='demo',
        help='Run mode: demo (run example tasks) or interactive (chat mode)'
    )
    
    args = parser.parse_args()
    
    if args.mode == 'demo':
        demo_research_tasks()
    else:
        interactive_mode()


if __name__ == "__main__":
    main()

